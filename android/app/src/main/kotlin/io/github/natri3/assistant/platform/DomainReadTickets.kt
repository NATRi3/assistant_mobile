package io.github.natri3.assistant.platform

import java.util.UUID
import io.github.natri3.assistant.security.DomainDtos

class DomainReadSuperseded:RuntimeException()
data class ClockSample(val elapsed:Long,val boot:Int,val lower:Long,val upper:Long,val clockGeneration:Long=0)
interface DomainClock {fun sample():ClockSample}
data class DomainTicket(val id:String,val sequence:Long,val epoch:Int,val operation:String,val resource:String?,val cursor:String?,val generation:Int,val scope:String,val stamp:ClockSample)
class DomainReadTickets(private val clock:DomainClock) {
    private val tickets=mutableMapOf<String,DomainTicket>()
    // Only IDs generated by this foreground instance can be ordinary cancellations.
    // Retain at most 256 original-deadline records, never bodies or credentials.
    private val cancelled=linkedMapOf<String,DomainTicket>()
    private var sequence=0L
    fun seedSequence(floor:Long){require(floor>=0);sequence=maxOf(sequence,floor)}
    private fun retire(t:DomainTicket){
        val now=clock.sample()
        cancelled.entries.removeAll{now.elapsed-it.value.stamp.elapsed !in 0 until 5000}
        cancelled[t.id]=t
        while(cancelled.size>256)cancelled.remove(cancelled.keys.first())
    }
    fun begin(epoch:Int,operation:String,resource:String?,cursor:String?,generation:Int,scope:String):DomainTicket {
        require(operation in setOf("getSelfDevice","getDashboard","getTask","getReminder"))
        require(generation>=0)
        if(operation=="getTask"||operation=="getReminder"){DomainDtos.uuid(resource);require(cursor==null)}
        else{require(resource==null);if(operation=="getSelfDevice")require(cursor==null)}
        if(cursor!=null)DomainDtos.text(cursor,1024,1)
        tickets[operation]?.let{retire(it)}
        val sample=clock.sample()
        val t=DomainTicket(UUID.randomUUID().toString(),maxOf(sequence+1,sample.elapsed).also{sequence=it},epoch,operation,resource,cursor,generation,scope,sample)
        tickets[operation]=t
        return t
    }
    fun requireTicket(id:String,epoch:Int,scope:String,validate:(DomainTicket)->Unit = {}):DomainTicket {
        val active=tickets.values.singleOrNull{it.id==id}
        val t=active?:cancelled[id]?:error("UNKNOWN_TICKET")
        val now=clock.sample()
        check(t.epoch==epoch&&t.scope==scope&&t.stamp.boot==now.boot&&t.stamp.clockGeneration==now.clockGeneration&&now.elapsed-t.stamp.elapsed in 0 until 5000&&now.lower<=t.stamp.upper&&t.stamp.lower<=now.upper)
        validate(t)
        if(active==null)throw DomainReadSuperseded()
        return t
    }
    fun consume(t:DomainTicket){check(tickets[t.operation]?.id==t.id);tickets.remove(t.operation)}
    fun supersedeOperation(operation:String){tickets[operation]?.let{retire(it);tickets.remove(operation)}}
    fun supersedeAll(except:DomainTicket?=null){
        val old=tickets.values.filter{it.id!=except?.id}.toList()
        old.forEach{retire(it);tickets.remove(it.operation)}
    }
    // Key/epoch/scope/lifecycle invalidation is deliberately not a benign drop.
    fun clear(){tickets.clear();cancelled.clear()}
    fun cancel(id:String){tickets.values.singleOrNull{it.id==id}?.let{retire(it);tickets.remove(it.operation)}}
}
